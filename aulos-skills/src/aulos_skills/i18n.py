def to_traditional(text: str) -> str:
    """Convert Simplified prose to Traditional Chinese (script + music terms)."""
    if not text:
        return ""
    out = text
    try:
        import zhconv

        out = zhconv.convert(out, "zh-hant")
    except Exception:  # noqa: BLE001
        pass
    for hans, hant in _HANT_PHRASE_MAP:
        out = out.replace(hans, hant)
    return out


def to_simplified(text: str) -> str:
    if not text:
        return ""
    try:
        import zhconv

        return zhconv.convert(text, "zh-hans")
    except Exception:  # noqa: BLE001
        return text


def _convert_tree(value: Any, *, to_hant: bool) -> Any:
    if isinstance(value, str):
        return to_traditional(value) if to_hant else to_simplified(value)
    if isinstance(value, list):
        return [_convert_tree(v, to_hant=to_hant) for v in value]
    if isinstance(value, dict):
        return {k: _convert_tree(v, to_hant=to_hant) for k, v in value.items()}
    return value


def extract_zh_layer(dossier: dict[str, Any] | None) -> dict[str, Any]:
    """Simplified Chinese layer (`zh` / `zh_hans`)."""
    return extract_chinese_layer(dossier, LANG_ZH_HANS)


def extract_chinese_layer(dossier: dict[str, Any] | None, lang: str) -> dict[str, Any]:
    d = dict(dossier or {})
    lang = normalize_lang(lang)
    keys = _HANS_KEYS if lang == LANG_ZH_HANS else _HANT_KEYS
    for key in keys:
        layer = d.get(key)
        if isinstance(layer, dict) and layer:
            return dict(layer)
    if lang == LANG_ZH_HANT:
        for key in _HANS_KEYS:
            layer = d.get(key)
            if isinstance(layer, dict) and layer:
                return _convert_tree(dict(layer), to_hant=True)
    return {}


def localize_view(dossier: dict[str, Any] | None, lang: str) -> dict[str, Any]:
    """Build a single-language view. English = top-level; Chinese = merge scaffold + layer."""
    lang = normalize_lang(lang)
    base = dict(dossier or {})
    for key in ("zh", "zh_hans", "zh_hant", "zh-Hans", "zh-Hant"):
        base.pop(key, None)
    if lang == LANG_EN:
        return base

    zh = extract_chinese_layer(dossier, lang)
    if not zh:
        return empty_dossier()
    scaffold = empty_dossier()
    for key in (
        "composer_portrait",
        "interpretations",
        "appreciation_videos",
        "vinyl_and_discography",
        "ambient_audio",
    ):
        if base.get(key):
            scaffold[key] = base[key]
    for key in ("catalog", "composer", "work_title", "era", "form"):
        if base.get(key):
            scaffold[key] = base[key]
            if lang == LANG_ZH_HANT and isinstance(scaffold[key], str):
                scaffold[key] = to_traditional(scaffold[key])
    return merge_dossiers(scaffold, zh)


def dossier_has_zh(dossier: dict[str, Any] | None) -> bool:
    """True if any Chinese prose pack exists (Hans or Hant)."""
    d = dict(dossier or {})
    for key in _HANS_KEYS + _HANT_KEYS:
        zh = d.get(key)
        if not isinstance(zh, dict):
            continue
        if zh.get("listening_thesis") or zh.get("work_introduction"):
            return True
        if zh.get("width_points") or zh.get("depth_points"):
            return True
        if zh.get("composer_profile"):
            return True
    return False


def prefer_chinese_variant(text: str) -> str:
    """Pick default Chinese UI variant from the listener's message script."""
    raw = text or ""
    if not re_has_cjk(raw):
        return LANG_ZH_HANS
    hant_markers = ("導賞", "聽", "聲", "樂", "變奏", "蕭邦", "貝多芬", "德弗札克", "馬勒", "請")
    hans_markers = ("导赏", "听", "声", "乐", "变奏", "肖邦", "贝多芬", "德沃夏克", "马勒")
    hant = sum(1 for m in hant_markers if m in raw)
    hans = sum(1 for m in hans_markers if m in raw)
    if hant > hans:
        return LANG_ZH_HANT
    return LANG_ZH_HANS


def re_has_cjk(text: str) -> bool:
    return bool(re.search(r"[\u4e00-\u9fff]", text or ""))


def merge_zh_into(target: dict[str, Any], zh_layer: dict[str, Any] | None) -> dict[str, Any]:
    """Merge into `zh` / `zh_hans` (simplified) slots."""
    out = dict(target or {})
    if not zh_layer:
        return out
    existing = extract_chinese_layer(out, LANG_ZH_HANS)
    merged = merge_dossiers(existing, zh_layer)
    out["zh"] = merged
    out["zh_hans"] = merged
    return out


def ensure_chinese_variants(dossier: dict[str, Any] | None) -> dict[str, Any]:
    """Ensure zh / zh_hans exist; synthesize zh_hant from simplified when missing."""
    out = dict(dossier or {})
    hans = extract_chinese_layer(out, LANG_ZH_HANS)
    if hans:
        out["zh"] = hans
        out["zh_hans"] = hans
    hant = None
    for key in _HANT_KEYS:
        if isinstance(out.get(key), dict) and out.get(key):
            hant = dict(out[key])
            break
    if hant:
        out["zh_hant"] = hant
    elif hans:
        out["zh_hant"] = _convert_tree(hans, to_hant=True)
    return out


def strip_tech_leaks_zh(text: str) -> str:
    """Light hygiene: avoid leaking raw English skill/ops jargon into Chinese copy."""
    banned = (
        "SkillRuntime",
        "corpus_hit",
        "llm_dossier",
        "width_points",
        "TODO",
        "FIXME",
        "null",
        "undefined",
    )
    out = text or ""
    for b in banned:
        out = out.replace(b, "")
    return out.strip()
