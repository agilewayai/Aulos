def is_chinese_lang(lang: str) -> bool:
    return (lang or "") in CHINESE_LANGS or (lang or "").startswith("zh")


def normalize_lang(lang: str | None) -> str:
    raw = (lang or "").strip()
    if raw in {"zh", "zh-Hans", "zh_hans", "zh-hans", "hans"}:
        return LANG_ZH_HANS
    if raw in {"zh-Hant", "zh_hant", "zh-hant", "hant"}:
        return LANG_ZH_HANT
    if raw in {LANG_ZH_HANS, LANG_ZH_HANT, LANG_EN}:
        return raw
    return LANG_EN


